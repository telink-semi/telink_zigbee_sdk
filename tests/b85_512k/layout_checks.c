/* Compile with the SDK target headers; no flashed test code. */
#include "tl_common.h"
#define CHECK(name, expr) typedef char check_##name[(expr) ? 1 : -1]
CHECK(chip, CHIP_TYPE == TLSR_8258_512K);
CHECK(no_bootloader, BOOT_LOADER_MODE == 0);
CHECK(app_base, FLASH_ADDR_OF_APP_FW == 0);
CHECK(ota_base, FLASH_ADDR_OF_OTA_IMAGE == 0x40000);
CHECK(slot_size, FLASH_OTA_IMAGE_MAX_SIZE == 208 * 1024);
CHECK(slot_a_end, FLASH_OTA_IMAGE_MAX_SIZE == NV_BASE_ADDRESS_ZB);
CHECK(slot_b_end, FLASH_ADDR_OF_OTA_IMAGE + FLASH_OTA_IMAGE_MAX_SIZE == NV_BASE_ADDRESS_BLE);
CHECK(ble_end, NV_BASE_ADDRESS_BLE + 0x2000 == FLASH_ADDR_OF_MAC_ADDR_512K);
CHECK(mac_end, FLASH_ADDR_OF_MAC_ADDR_512K + 0x1000 == FLASH_ADDR_OF_F_CFG_INFO_512K);
CHECK(cfg_end, FLASH_ADDR_OF_F_CFG_INFO_512K + 0x1000 == CFG_PRE_INSTALL_CODE);
CHECK(install_end, CFG_PRE_INSTALL_CODE + 0x1000 == CFG_FACTORY_RST_CNT);
CHECK(reset_end, CFG_FACTORY_RST_CNT + 0x1000 == MODULES_START_ADDR(NV_MODULE_APP));
#define CHECK_MODULE(id, next) CHECK(module_##id##_end, MODULE_SECT_END(id, 1) == MODULES_START_ADDR(next))
CHECK_MODULE(NV_MODULE_ZB_INFO, NV_MODULE_ADDRESS_TABLE);
CHECK_MODULE(NV_MODULE_ADDRESS_TABLE, NV_MODULE_APS);
CHECK_MODULE(NV_MODULE_APS, NV_MODULE_ZCL);
CHECK_MODULE(NV_MODULE_ZCL, NV_MODULE_NWK_FRAME_COUNT);
CHECK_MODULE(NV_MODULE_NWK_FRAME_COUNT, NV_MODULE_OTA);
CHECK(nv_low_end, MODULE_SECT_END(NV_MODULE_OTA, 1) == FLASH_ADDR_OF_OTA_IMAGE);
CHECK_MODULE(NV_MODULE_APP, NV_MODULE_KEYPAIR);
CHECK(nv_high_end, MODULE_SECT_END(NV_MODULE_KEYPAIR, 1) == 512 * 1024);
CHECK(keypair_index_size, MODULE_INFO_SIZE(NV_MODULE_KEYPAIR) == 1024);
CHECK(keypair_payload_room, MODULE_INFO_SIZE(NV_MODULE_KEYPAIR) < NV_SECTOR_SIZE(NV_MODULE_KEYPAIR));
